def c_escape(s):
    out = []
    for ch in s:
        if ord(ch) < 128:
            out.append(ch)
        else:
            out.extend('\\x%02X' % b for b in ch.encode('utf-8'))
    # a hex escape eats following hex digits: split the literal after one
    res, i = '', 0
    joined = ''.join(out)
    j = 0
    while j < len(joined):
        if joined.startswith('\\x', j) and j + 4 <= len(joined):
            res += joined[j:j + 4]
            j += 4
            if j < len(joined) and joined[j] in '0123456789abcdefABCDEF' and not joined.startswith('\\x', j):
                res += '" "'
            continue
        res += joined[j]
        j += 1
    return res


